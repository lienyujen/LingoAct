"""Export compact, attributed vocabulary facts for English Edge Functions."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'data/english/lingoact-vocabulary.json').read_text(encoding='utf-8'))
catalog = json.loads((ROOT / 'data/english/catalog.json').read_text(encoding='utf-8'))
rows = [[e['lemma'], min(e['ceec_bands']) if e['ceec_bands'] else 0,
         'basic1200' in e['school_lists'], 'additional800' in e['school_lists'], e['topics'], e['collocations']]
        for e in data['entries'] if e['lemma'].strip()]
out = ROOT / 'supabase/functions/_shared/english-vocabulary.generated.ts'
out.write_text('// Generated by scripts/build-english-runtime.py. Noncommercial CEEC reference;\n'
    '// attribution and source restrictions: supabase/licenses/english-vocabulary-NOTICE.txt.\n'
    'export const ENGLISH_VOCABULARY: Array<[string, number, boolean, boolean, string[], string[]]> = '
    + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + '\n'
    + 'export const ENGLISH_CEFR = ' + json.dumps(catalog['cefr_levels'], ensure_ascii=False) + '\n', encoding='utf-8')
print(f'Exported {len(rows)} English vocabulary entries.')
