// The font's candidate order is its IVS contract. Keep the matching dictionary
// in schema.sql so a teacher's self-deploy cannot create an empty lookup table.
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const revision = 'fa20c2bb5e2986856974f00c93a662d0805c92a0'
const base = `https://raw.githubusercontent.com/ButTaiwan/bpmfvs/${revision}`
async function download(name) {
  const response = await fetch(`${base}/${name}`)
  if (!response.ok) throw new Error(`${response.status}: ${name}`)
  return response.text()
}
const table = await download('phonetic/phonic_table_Z.txt')
const entries = table.trim().split(/\r?\n/u).map((line) => {
  const [character, hex, , ...readings] = line.split('\t')
  const codepoint = parseInt(hex, 16)
  assert.equal(character.codePointAt(0), codepoint)
  assert.ok(readings.length && readings.every((reading) => reading.trim()))
  return { codepoint, readings }
})
assert.equal(entries.length, 18636)
assert.equal(new Set(entries.map((entry) => entry.codepoint)).size, entries.length)
const quote = (value) => `'${value.replaceAll("'", "''")}'`
const begin = '-- BEGIN GENERATED BOPOMOFO READINGS'
const end = '-- END GENERATED BOPOMOFO READINGS'
const block = [
  begin,
  '-- ButTaiwan/bpmfvs, Apache 2.0; see supabase/licenses/bpmfvs-NOTICE.txt.',
  `-- Source revision: ${revision}; generated by scripts/generate-bopomofo-readings.mjs.`,
  '-- Never sort candidates: index n must keep selecting the same IVS glyph.',
  'insert into public.bopomofo_readings (codepoint, readings) values',
  entries.map(({ codepoint, readings }) => `  (${codepoint}, array[${readings.map(quote).join(',')}])`).join(',\n'),
  'on conflict (codepoint) do update set readings = excluded.readings;',
  end,
].join('\n')
const file = path.join(root, 'supabase/schema.sql')
let schema = fs.readFileSync(file, 'utf8')
if (schema.includes(begin)) {
  schema = schema.slice(0, schema.indexOf(begin)) + block + schema.slice(schema.indexOf(end) + end.length)
} else {
  const anchor = 'grant all on public.bopomofo_readings to service_role;'
  assert.ok(schema.includes(anchor))
  schema = schema.replace(anchor, `${anchor}\n\n${block}`)
}
fs.writeFileSync(file, schema)
const licenses = path.join(root, 'supabase/licenses')
fs.mkdirSync(licenses, { recursive: true })
fs.writeFileSync(path.join(licenses, 'bpmfvs-LICENSE-2.0.txt'), await download('LICENSE-2.0.txt'))
fs.writeFileSync(path.join(licenses, 'bpmfvs-NOTICE.txt'), await download('NOTICE.txt'))
console.log(`Seeded ${entries.length} font-ordered readings into schema.sql.`)
