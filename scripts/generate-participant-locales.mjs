// Translates the student page's English strings into the guidance languages that
// have no hand-written column, and rewrites src/lib/participantLocales.generated.ts.
//
// Run after changing any English string:
//   node scripts/generate-participant-locales.mjs
//
// The Gemini key is read from supabase/.env rather than the environment, because
// that file is already where this repository keeps it and is already gitignored.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = path.join(root, 'src/lib/participantI18n.ts')
const outputPath = path.join(root, 'src/lib/participantLocales.generated.ts')

// Every locale in GUIDANCE_LOCALES except the two written by hand.
const targets = [
  { code: 'ja', name: 'Japanese' },
  { code: 'ko', name: 'Korean' },
  { code: 'es', name: 'Spanish' },
  { code: 'fr', name: 'French' },
  { code: 'de', name: 'German' },
  { code: 'vi', name: 'Vietnamese' },
]

function geminiKey() {
  const envPath = path.join(root, 'supabase/.env')
  if (!fs.existsSync(envPath)) throw new Error('supabase/.env not found — it holds GEMINI_API_KEY.')
  const line = fs.readFileSync(envPath, 'utf8').split(/\r?\n/).find((l) => l.startsWith('GEMINI_API_KEY='))
  const key = line ? line.slice('GEMINI_API_KEY='.length).trim() : ''
  if (!key || key.startsWith('your-')) throw new Error('GEMINI_API_KEY in supabase/.env is missing or still a placeholder.')
  return key
}

// The catalogue is a plain object literal, so the English column can be lifted
// out and evaluated rather than parsed. Reaching for a TypeScript parser here
// would pull a toolchain into a script that runs a handful of times a year.
function englishStrings() {
  const source = fs.readFileSync(sourcePath, 'utf8')
  const start = source.indexOf('\n  en: {')
  if (start < 0) throw new Error('could not find the English column in participantI18n.ts')
  const open = source.indexOf('{', start)
  let depth = 0
  let end = -1
  for (let i = open; i < source.length; i += 1) {
    if (source[i] === '{') depth += 1
    else if (source[i] === '}') { depth -= 1; if (depth === 0) { end = i; break } }
  }
  if (end < 0) throw new Error('unbalanced braces in the English column')
  // eslint-disable-next-line no-new-func
  return new Function(`return ${source.slice(open, end + 1)}`)()
}

async function translate(key, strings, target) {
  const prompt = [
    `Translate this UI string catalogue for LingoAct, a live classroom tool, into ${target.name}.`,
    'The readers are students in a language class. Keep every translation as short as the English,',
    'because these render as buttons, labels and inline hints. Preserve leading and trailing spaces',
    'exactly, keep punctuation style natural for the target language, and do not translate the',
    'product name LingoAct or the term "Exit Ticket". Return a JSON object with exactly the same',
    'keys as the input and translated string values, nothing else.',
    '',
    JSON.stringify(strings, null, 2),
  ].join('\n')

  const response = await fetch(
    'https://generativelanguage.googleapis.com/v1beta/models/gemini-3.7-flash:generateContent',
    {
      method: 'POST',
      headers: { 'x-goog-api-key': key, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{ parts: [{ text: prompt }] }],
        generationConfig: { responseMimeType: 'application/json', temperature: 0.2 },
      }),
    },
  )
  if (!response.ok) throw new Error(`${target.code}: Gemini returned ${response.status} ${(await response.text()).slice(0, 200)}`)
  const payload = await response.json()
  const text = payload.candidates?.[0]?.content?.parts?.map((p) => p.text || '').join('') || ''
  const translated = JSON.parse(text)

  const missing = Object.keys(strings).filter((k) => typeof translated[k] !== 'string')
  if (missing.length) throw new Error(`${target.code}: ${missing.length} keys missing, first is "${missing[0]}"`)
  return translated
}

const key = geminiKey()
const strings = englishStrings()
console.log(`English catalogue: ${Object.keys(strings).length} keys`)

const generated = {}
for (const target of targets) {
  process.stdout.write(`  ${target.code} (${target.name})... `)
  generated[target.code] = await translate(key, strings, target)
  console.log(`${Object.keys(generated[target.code]).length} keys`)
}

const banner = `// Generated by scripts/generate-participant-locales.mjs — do not edit by hand.
//
// Traditional Chinese and English live in participantI18n.ts because they are
// proofread; these are machine translations of the English column. Keeping them
// in a separate file means regenerating cannot damage the hand-written source,
// and a missing key here simply falls back to English rather than breaking.
export const generatedLocales: Record<string, Record<string, string>> = `

fs.writeFileSync(outputPath, `${banner}${JSON.stringify(generated, null, 2)}\n`)
console.log(`wrote ${path.relative(root, outputPath)}`)
