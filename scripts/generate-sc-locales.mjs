// Build-time conversion only: the SC application does not load OpenCC for UI.
import fs from 'node:fs'
import ts from 'typescript'
import { Converter } from 'opencc-js'
import { mainlandTerms, presenterCopy, participantCopy } from './mainland-ui-copy.mjs'

const convert = Converter({ from: 'twp', to: 'cn' })
const mainland = (text) => mainlandTerms(convert(text)).replaceAll('擷取', '提取')

function readMessages(file) {
  const source = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true)
  let result
  function visit(node) {
    if (ts.isVariableDeclaration(node) && node.name.getText(source) === 'messages') {
      const initializer = ts.isAsExpression(node.initializer) ? node.initializer.expression : node.initializer
      result = Object.fromEntries(initializer.properties.map((column) => [column.name.text,
        Object.fromEntries(column.initializer.properties.filter(ts.isPropertyAssignment).map((entry) => [entry.name.text, entry.initializer.text]))]))
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
  if (!result?.['zh-TW']) throw new Error(`No messages in ${file}`)
  return result
}
const presenter = readMessages('src/lib/presenterI18n.ts')
const participant = readMessages('src/lib/participantI18n.ts')
const simplified = (column) => Object.fromEntries(Object.entries(column).map(([key, value]) => [key, mainland(value)]))
fs.writeFileSync('src/lib/scLocales.generated.ts', '// Generated by scripts/generate-sc-locales.mjs; no runtime conversion.\n'
  + `export const scPresenterMessages: Record<string, string> = ${JSON.stringify({ ...simplified(presenter['zh-TW']), ...presenterCopy }, null, 2)}\n`
  + `export const scParticipantMessages: Record<string, string> = ${JSON.stringify({ ...simplified(participant['zh-TW']), ...participantCopy }, null, 2)}\n`)
console.log(`SC catalogues: ${Object.keys(presenter['zh-TW']).length} teacher, ${Object.keys(participant['zh-TW']).length} student strings`)
