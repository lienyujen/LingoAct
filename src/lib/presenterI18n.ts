export type PresenterMessageKey = keyof (typeof messages)['zh-TW']

export function presenterText(
  locale: PresenterLocale,
  key: PresenterMessageKey,
  values?: Record<string, string | number>,
) {
  const template = (locale === 'zh-TW' || locale === 'en')
    ? messages[locale][key]
    : generatedPresenterLocales[locale]?.[key] ?? messages.en[key]
  if (!values) return template
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (
    name in values ? String(values[name]) : whole
  ))
}

const presenterLocales: readonly string[] = ['zh-TW', 'en', 'ja', 'ko', 'es', 'fr', 'de', 'vi']

// The track carries a language code in the caption pipeline's lower-case
// spelling; the locale tables key on BCP-47. Converting here rather than
// renaming either side keeps rows already written valid.
export function presenterLocaleFor(teachingLanguage: string | null | undefined): PresenterLocale {
  const language = resolveTrack(teachingLanguage).language
  const normalised = language === 'zh-tw' ? 'zh-TW' : language
  return (presenterLocales.includes(normalised) ? normalised : 'zh-TW') as PresenterLocale
}

// The desktop app opens 自訂測驗檢視 in its own window, which mounts a second
// React root with no provider above it and never loads the session row. The
// locale rides along in localStorage the way the presenter token already does:
// both windows are the same origin, and the class it belongs to is in the key.
const LOCALE_PREFIX = 'lingoact:presenter-locale:'

export function savePresenterLocale(sessionId: string, locale: PresenterLocale) {
  window.localStorage.setItem(`${LOCALE_PREFIX}${sessionId}`, locale)
}

export function storedPresenterLocale(sessionId: string): PresenterLocale {
  const stored = window.localStorage.getItem(`${LOCALE_PREFIX}${sessionId}`)
  return (stored && presenterLocales.includes(stored) ? stored : 'zh-TW') as PresenterLocale
}

// A context rather than a prop on fifteen components: the locale is a property
// of the class, not of any one panel, and threading it by hand would touch
// every call site every time a component moves.
export const PresenterLocaleContext = createContext<PresenterLocale>('zh-TW')

// Named because module-level helpers take it as an argument: a function that
// formats an error message cannot call a hook, but it can be handed the same
// lookup the component is using.
export type PresenterT = (key: PresenterMessageKey, values?: Record<string, string | number>) => string

export function presenterTextFor(locale: PresenterLocale): PresenterT {
  return (key, values) => presenterText(locale, key, values)
}

// Cached per locale rather than rebuilt each render: a component that puts `t`
// in a useCallback's dependencies would otherwise rebuild that callback every
// render, and a loader in one of those would refetch forever.
const lookups = new Map<PresenterLocale, PresenterT>()

export function presenterLookup(locale: PresenterLocale): PresenterT {
  const cached = lookups.get(locale)
  if (cached) return cached
  const lookup = presenterTextFor(locale)
  lookups.set(locale, lookup)
  return lookup
}

export function usePresenterText(): PresenterT {
  return presenterLookup(useContext(PresenterLocaleContext))
}

export function usePresenterLocale() {
  return useContext(PresenterLocaleContext)
}
